package com.pocketpad.app.input

/**
 * Zero-based button indices matching the HID report descriptor.
 * Button N in the descriptor is index N-1 here.
 */
object Buttons {
    const val A = 0
    const val B = 1
    const val X = 2
    const val Y = 3
    const val LB = 4
    const val RB = 5
    const val BACK = 6
    const val START = 7
    const val GUIDE = 8
    const val L3 = 9
    const val R3 = 10
    const val COUNT = 16
}
